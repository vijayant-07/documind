CREATE TABLE analysis_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT,
    repository_full_name VARCHAR(255) NOT NULL,
    pull_request_number INT NOT NULL,
    base_branch VARCHAR(255),
    head_sha VARCHAR(64),
    merge_sha VARCHAR(64),
    idempotency_key VARCHAR(255) NOT NULL,
    github_delivery_id VARCHAR(100),
    status VARCHAR(50) NOT NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE,
    documentation_pull_request_number INT,
    documentation_pull_request_url VARCHAR(500),
    last_error VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_analysis_jobs_idempotency_key UNIQUE (idempotency_key)
);

CREATE INDEX idx_analysis_jobs_status ON analysis_jobs (status);
CREATE INDEX idx_analysis_jobs_repo_pr ON analysis_jobs (repository_full_name, pull_request_number);
CREATE INDEX idx_analysis_jobs_delivery_id ON analysis_jobs (github_delivery_id);
